"""Import scanner snapshots from discovery/raw/ into discovery/normalized/ and write an import report.

Reads only. Nothing from a snapshot is downloaded, compiled or executed.

    python tools/discovery/importer.py [--root .]
"""
import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import yaml  # noqa: E402
from normalize import normalize_cve  # noqa: E402


def load_snapshots(raw: Path) -> list[tuple[str, dict]]:
    snaps = []
    for f in sorted(raw.glob("*/results.json")):
        doc = json.loads(f.read_text())
        snaps.append((f.parent.name, doc))
    snaps.sort(key=lambda s: s[1]["summary"]["generated_utc"])
    return snaps


def load_registry(path: Path) -> dict[str, dict]:
    doc = yaml.safe_load(path.read_text()) or {}
    return {str(e["cve_id"]).upper(): e for e in doc.get("entries", []) if "cve_id" in e}


def enrich(vuln: dict, reg: dict) -> None:
    """Fill fields the scan left empty (e.g. a single-CVE scan) from the registry entry."""
    for field, key in (("component", "component"), ("subsystem", "subsystem"),
                       ("category", "class"), ("severity", "severity")):
        if not vuln[field] and reg.get(key):
            vuln[field] = str(reg[key])


def write_jsonl(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(r, sort_keys=False) + "\n" for r in rows))


def report(snaps, vulns, arts) -> str:
    level = Counter(a["discovery"]["level"] for a in arts)
    cand = [a for a in arts if a["discovery"]["is_reproduction_candidate"]]
    cand_level = Counter(a["discovery"]["level"] for a in cand)
    cand_class = Counter(a["discovery"]["class"] for a in cand)
    by_url = defaultdict(set)
    for a in arts:
        by_url[a["artifact"]["source_url"].rstrip("/").lower()].add(a["cve"])
    shared = sum(1 for cves in by_url.values() if len(cves) > 1)
    # The scanner's own identity collapses all files of one GitHub repo / GitLab project per CVE.
    repo_level = {(a["cve"], (a["artifact"]["repository"] or a["artifact"]["source_url"]).lower()) for a in cand}
    no_cand = [v["cve"] for v in vulns if not v["reproduction_candidate_count"]]
    rows = lambda c: "\n".join(f"| {k} | {n} |" for k, n in sorted(c.items(), key=lambda x: -x[1]))  # noqa: E731
    return f"""# Import report

Generated by `tools/discovery/importer.py`. Snapshots imported: {", ".join(f"`{n}`" for n, _ in snaps)}.

| Metric | Value |
| --- | --- |
| Vulnerabilities | {len(vulns)} |
| Artifact records (deduplicated per CVE by URL) | {len(arts)} |
| Reproduction candidates (file-level identity) | {len(cand)} |
| Reproduction candidates (scanner's repository-level identity) | {len(repo_level)} |
| Artifact URLs shared by more than one CVE | {shared} |
| CVEs without a reproduction candidate | {len(no_cand)} |
| Lab-validated | 0 |

All records are `DISCOVERED`. Candidates are leads, not confirmed PoCs.

The scanner's "unique reproduction candidates" figure (617 for the initial scan) counts one per repository
per CVE. This importer keeps each file URL as its own artifact record, so its candidate count is higher.
The repository-level row reconciles the two.

## Reproduction candidates by level

| Level | Count |
| --- | --- |
{rows(cand_level)}

`file` is a direct source file, `repository` is a whole repository, `commit` is a commit, `other` is anything
else (gists, pages, other hosts). Only `file` candidates can be retrieved directly; the rest need resolving.

## Reproduction candidates by class

| Class | Count |
| --- | --- |
{rows(cand_class)}

## All artifact records by level

| Level | Count |
| --- | --- |
{rows(level)}

## CVEs without a reproduction candidate

{", ".join(no_cand) if no_cand else "None."}
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=Path("."))
    root = ap.parse_args().root
    snaps = load_snapshots(root / "discovery/raw")
    registry = load_registry(root / "discovery/registry/registry.yaml")
    vulns: dict[str, dict] = {}
    arts: dict[str, list[dict]] = {}
    for name, doc in snaps:  # later snapshots replace earlier ones per CVE
        for entry in doc["results"]:
            v, a = normalize_cve(entry, name)
            enrich(v, registry.get(v["cve"], {}))
            vulns[v["cve"]], arts[v["cve"]] = v, a
    vlist = sorted(vulns.values(), key=lambda v: v["cve"])
    alist = [a for cve in sorted(arts) for a in arts[cve]]
    out = root / "discovery/normalized"
    write_jsonl(out / "vulnerabilities.jsonl", vlist)
    write_jsonl(out / "artifacts.jsonl", alist)
    (root / "discovery/reports").mkdir(exist_ok=True)
    (root / "discovery/reports/import-report.md").write_text(report(snaps, vlist, alist))
    print(f"{len(vlist)} vulnerabilities, {len(alist)} artifacts")


if __name__ == "__main__":
    main()
