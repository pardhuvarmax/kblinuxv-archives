"""Generate README.md files for the CVE folders and artifact folders under corpus/.

Offline: reads metadata/*.jsonl only (build them with generate_metadata.py and acquire_artifacts.py).

    python tools/processing/generate_readmes.py [--root .]
"""
import argparse
import html
import json
from pathlib import Path


def jl(path: Path) -> list[dict]:
    return [json.loads(x) for x in path.read_text().splitlines()] if path.is_file() else []


def esc(s) -> str:
    return html.escape(str(s if s is not None else ""), quote=False).replace("|", "\\|")


def md_link(url: str) -> str:
    from urllib.parse import quote
    return quote(url, safe=":/?&=#%@+~-._")


def cve_readme(v: dict, stored: list[dict], other: list[dict], prov: dict) -> str:
    nvd, reg = v.get("nvd") or {}, v.get("registry") or {}
    cvss = nvd.get("cvss")
    score = f"{cvss['score']} {cvss['severity'] or ''} (CVSS {cvss['version']}, `{cvss['vector']}`)" if cvss else "not in NVD record"
    aff = reg.get("affected") or {}
    lines = [f"# {v['cve']}", "",
             f"*{esc(v.get('component'))} / {esc(v.get('subsystem'))}, class `{esc(v.get('category'))}`*", "",
             "| Field | Value |", "| --- | --- |",
             f"| NVD | [{v['cve']}](https://nvd.nist.gov/vuln/detail/{v['cve']}) |",
             f"| Severity | {esc(score)} |",
             f"| Published / modified | {esc((nvd.get('published') or '?')[:10])} / {esc((nvd.get('last_modified') or '?')[:10])} |",
             f"| NVD status | {esc(nvd.get('status') or 'no NVD record')} |",
             f"| Weakness (CWE) | {esc(', '.join(nvd.get('cwe') or []) or 'not assigned')} |",
             f"| Affected (registry) | {esc(aff.get('ranges') or 'not confirmed')} |",
             f"| Fixed in (registry) | {esc(reg.get('fixed_in') or 'unknown')} |", ""]
    if nvd.get("description"):
        d = nvd["description"].strip()
        lines += ["## Description (NVD)", "", "> " + esc(d[:2500] + (" ..." if len(d) > 2500 else "")).replace("\n", "\n> "), ""]
    if reg.get("summary"):
        lines += ["## Registry summary", "", esc(reg["summary"]), ""]
    lines += ["## Artifacts in this folder", "",
              "| Artifact | File | Type | Source (pinned) | License | SHA-256 | State |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for a in stored:
        p = prov[a["artifact_id"]]
        lines.append(f"| `{a['artifact_id']}` | [`{esc(Path(a['redistribution']['stored_path']).name)}`]({a['artifact_id']}/) | "
                     f"{esc(a['artifact']['type'])} | [{esc(p['repository'])}]({md_link(p['source_url'])}) | "
                     f"{esc(p['license'] or 'none')} | `{p['sha256'][:12]}…` | {esc(a['verification']['state'])} |")
    lines += [""]
    if other:
        lines += ["## Other retrieved artifacts for this CVE (not stored here)", "",
                  "Retrieved and hashed but kept out of the repository because the source has no redistributable license.", "",
                  "| Artifact | File | Source (pinned) | SHA-256 |", "| --- | --- | --- | --- |"]
        for a in other:
            p = prov[a["artifact_id"]]
            lines.append(f"| `{a['artifact_id']}` | `{esc(Path(p['path']).name)}` | [{esc(p['repository'])}]({md_link(p['source_url'])}) | `{p['sha256'][:12]}…` |")
        lines += [""]
    refs = list(dict.fromkeys((reg.get("references") or []) + [r["url"] for r in nvd.get("references", [])]))
    if refs:
        lines += ["## References", ""] + [f"- <{u}>" for u in refs[:20]] + (
            [f"- ... and {len(refs) - 20} more in `metadata/vulnerabilities.jsonl`"] if len(refs) > 20 else []) + [""]
    lines += ["## Sources and status", "",
              f"Vulnerability data: NVD API and the KB-LVA registry, retrieved {esc((v.get('retrieved_at') or '')[:10])}. "
              "Artifact data: `metadata/provenance.jsonl`. This README is generated by `tools/processing/generate_readmes.py`.", "",
              "Artifacts are `RETRIEVED` only: not source-reviewed and not lab-validated. They may be exploits. "
              "Do not run them outside an isolated, disposable lab. Licenses are repository-level and not verified per file.", ""]
    return "\n".join(lines)


def artifact_readme(a: dict, p: dict) -> str:
    name = Path(a["redistribution"]["stored_path"]).name
    return f"""# {a['artifact_id']}

`{esc(name)}` for [{a['cve']}](../README.md).

| Field | Value |
| --- | --- |
| Type | {esc(a['artifact']['type'])} ({esc(a['artifact'].get('language') or 'unknown language')}) |
| Repository | [{esc(p['repository'])}](https://{p['source_url'].split('/')[2]}/{esc(p['repository'])}) (owner `{esc(p.get('repository_owner'))}`) |
| Pinned file | [{esc(p['path'])}]({md_link(p['source_url'])}) at commit `{p['commit']}` |
| License | {esc(p['license'] or 'none')} ({esc(p['license_scope'])}) |
| Retrieved | {esc(p['retrieved_at'])} |
| SHA-256 | `{p['sha256']}` |
| State | {esc(a['verification']['state'])} |

Verify: `sha256sum -c manifests/SHA256SUMS` from the repository root. Original attribution and license apply; the file is
unmodified. Do not run it outside an isolated lab.
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=Path("."))
    root = ap.parse_args().root
    arts = jl(root / "metadata/artifacts.jsonl")
    prov = {p["artifact_id"]: p for p in jl(root / "metadata/provenance.jsonl")}
    vulns = {v["cve"]: v for v in jl(root / "metadata/vulnerabilities.jsonl")}
    n = 0
    for cve in sorted({a["cve"] for a in arts}):
        mine = [a for a in arts if a["cve"] == cve]
        stored = [a for a in mine if a["redistribution"].get("stored_path")]
        if not stored:
            continue
        folder = (root / stored[0]["redistribution"]["stored_path"]).parent.parent
        (folder / "README.md").write_text(cve_readme(vulns[cve], stored, [a for a in mine if a not in stored], prov))
        for a in stored:
            (root / a["redistribution"]["stored_path"]).parent.joinpath("README.md").write_text(artifact_readme(a, prov[a["artifact_id"]]))
            n += 1
        n += 1
    print(f"{n} READMEs written")


if __name__ == "__main__":
    main()
