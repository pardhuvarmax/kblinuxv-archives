package docs

import (
	"fmt"
	"os"
	"strings"

	"github.com/pardhuvarmax/kblinuxv-archives/internal/data"
	"github.com/pardhuvarmax/kblinuxv-archives/internal/stats"
)

// Markers delimit the part of the root README that kblva rewrites.
const (
	StatusStart = "<!-- kblva:status:start -->"
	StatusEnd   = "<!-- kblva:status:end -->"
)

func comma(n int) string {
	s := fmt.Sprint(n)
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	return s
}

// StatusBlock renders the status table. It contains nothing machine-specific (no counts of files on disk, no
// dates), so a clean checkout and the author's machine produce the same text.
func StatusBlock(s stats.Status) string {
	return fmt.Sprintf(`%s
_Generated by `+"`kblva docs`"+` from the data in this repository. Do not edit between the markers._

| Metric | Value |
| --- | --- |
| Registered CVEs | %s |
| Scan snapshots | %d |
| Artifact records | %s |
| Reproduction candidates (file-level) | %s |
| Candidates `+"`ready`"+` / `+"`needs-review`"+` / `+"`needs-resolution`"+` | %s / %s / %s |
| Acquisition batches | %d |
| Artifacts retrieved | %d (%d stored in `+"`corpus/`"+`, %d local-only) |
| Source-reviewed / rejected | %d / %d |
| Lab-validated | %d |
%s`, StatusStart, comma(s.RegisteredCVEs), len(s.Snapshots), comma(s.ArtifactRecords), comma(s.CandidateTotal),
		comma(s.Candidates["ready"]), comma(s.Candidates["needs-review"]), comma(s.Candidates["needs-resolution"]), s.Batches,
		s.Retrieved, s.Stored, s.LocalOnlyRecords, s.States["SOURCE_REVIEWED"], s.States["REJECTED"], s.States["LAB_VALIDATED"], StatusEnd)
}

// Splice replaces the text between the status markers in readme. ok is false if the markers are missing.
func Splice(readme, block string) (out string, ok bool) {
	i := strings.Index(readme, StatusStart)
	j := strings.Index(readme, StatusEnd)
	if i < 0 || j < i {
		return readme, false
	}
	return readme[:i] + block + readme[j+len(StatusEnd):], true
}

// UpdateStatus rewrites the status block in the root README from the current data. found is false if the README
// has no markers (nothing is touched); changed says whether the file's content changed.
func UpdateStatus(r data.Repo) (changed, found bool, err error) {
	path := r.P("README.md")
	b, err := os.ReadFile(path)
	if err != nil {
		return false, false, err
	}
	s, err := stats.Compute(r)
	if err != nil {
		return false, true, err
	}
	out, ok := Splice(string(b), StatusBlock(s))
	if !ok {
		return false, false, nil
	}
	if out == string(b) {
		return false, true, nil
	}
	return true, true, os.WriteFile(path, []byte(out), 0o644)
}
